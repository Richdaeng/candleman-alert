def intro_card(base, kind=None):
    """#종목설명에 올릴 소개 카드(디스코드 embed)."""
    name = COINS.get(base) or STOCKS.get(base) or OTHERS.get(base)
    title = "🆕 %s · %s" % (base, name) if name and name != base else "🆕 %s" % base
    desc = DESCRIPTIONS.get(base)
    if not desc:
        desc = ("%s. " % KIND_WORDS[kind] if kind in KIND_WORDS else "") + "자세한 설명은 곧 추가함."
    return {"title": title, "description": desc, "color": 2533018, "footer": {"text": "처음 거래한 종목"}}


def label(base):
    """'비트코인(BTC)' · '한국 주식 ETF(EWY)' · 모르는 종목은 기호만."""
    name = COINS.get(base) or STOCKS.get(base) or OTHERS.get(base)
    return "%s(%s)" % (name, base) if name and name != base else base


def amount(q, base):
    """수량 글자: 주식 · ETF 는 '66.74주', 나머지는 '0.05 BTC'."""
    if base in STOCKS:
        return "%s주" % fmt.qty(q)
    return "%s %s" % (fmt.qty(q), base)
